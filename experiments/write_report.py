#!/usr/bin/env python3
"""Build docs/results.md from results/*.csv (no hand-typed numbers)."""
import sys
from pathlib import Path
import pandas as pd
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT
RES, DOCS = ROOT / "results", ROOT / "docs"

def tab(df, fmt):
    cols = list(df.columns)
    out = "| " + " | ".join(cols) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    for _, r in df.iterrows():
        out += "| " + " | ".join(fmt.get(c, str)(r[c]) if pd.notna(r[c]) else "n/a" for c in cols) + " |\n"
    return out

cons = pd.read_csv(RES / "consolidated_results.csv")
cmp_ = pd.read_csv(RES / "paper_comparison.csv")
ag = pd.read_csv(RES / "paper_agreement.csv")
sw = pd.read_csv(RES / "sweep_summary.csv")
s54p = pd.read_csv(RES / "section54_process.csv")
s54s = pd.read_csv(RES / "section54_system.csv")
mainsys = pd.read_csv(RES / "main_system.csv")
n = lambda v: f"{v:,.0f}"; d2 = lambda v: f"{v:.2f}"; p0 = lambda v: f"{v:+.0f}%"

t = "# Results (generated by experiments/write_report.py - do not edit by hand)\n\n"
t += ("All workloads are SYNTHETIC approximations scaled to 1/8; times are simulated ticks. Numbers below are "
      "**measured by this simulator**, except the columns labelled *paper*, which are the published Table 2 values.\n\n")
t += "## 1. Measured: baseline vs token-ordered LRU (mean of seeds)\n\n"
c = cons.assign(shortage=(cons.shortage * 100).round().astype(int).astype(str) + "%")
c = c[["label", "program", "shortage", "base_major_faults_mean", "tok_major_faults_mean", "pf_reduction_pct_of_means",
       "base_slowdown_mean", "tok_slowdown_mean", "sd_reduction_pct_of_means", "seeds_token_better_faults",
       "seeds_token_better_slowdown", "n_seeds"]]
t += tab(c, dict(base_major_faults_mean=n, tok_major_faults_mean=n, pf_reduction_pct_of_means=p0, base_slowdown_mean=d2,
                 tok_slowdown_mean=d2, sd_reduction_pct_of_means=p0))
t += "\n`seeds_token_better_*` = number of seeds (out of n_seeds) in which the token policy beat the baseline for that process.\n\n"
t += "## 2. Paper Table 2 vs this implementation\n\n"
for metric in ("major page faults", "slowdown"):
    m = cmp_[cmp_.metric == metric]
    f = n if metric.startswith("major") else d2
    m = m[["pair", "program", "paper_baseline", "paper_token", "paper_reduction_pct", "our_baseline", "our_token",
           "our_reduction_pct", "abs_diff_baseline", "abs_diff_token", "reduction_diff_points", "direction_agrees"]]
    t += f"### {metric}\n\n" + tab(m, dict(paper_baseline=f, paper_token=f, our_baseline=f, our_token=f,
         abs_diff_baseline=f, abs_diff_token=f, paper_reduction_pct=lambda v: f"{v:+.0f}%",
         our_reduction_pct=lambda v: f"{v:+.0f}%", reduction_diff_points=lambda v: f"{v:+.0f} pts")) + "\n"
t += "### Agreement summary\n\n" + tab(ag, dict(mean_abs_reduction_diff_points=lambda v: f"{v:.0f} pts")) + "\n"
t += ("**How to read this honestly.** Absolute page-fault counts differ by construction (1/8-scale synthetic traces vs real "
      "SPEC2000 on Linux 2.2), so only the *reduction percentages* and the *direction* of change are comparable, and even "
      "those only loosely. Differences have known causes: exact LRU instead of Linux's reference-bit approximation; "
      "synthetic access patterns; a single shared FIFO disk with fixed service time; no write-back; per-pair shortage chosen "
      "by our own baseline-only criterion; and the paper's Linux scheduler/readahead/swap-cache behaviour, none of which is modelled. "
      "This is directional agreement, not numerical reproduction.\n\n")
t += "## 3. Memory-pressure sweep (both policies, mean over seeds)\n\n"
t += tab(sw[["pair", "shortage", "base_total_faults", "tok_total_faults", "total_fault_reduction_pct", "base_mean_slowdown",
             "tok_mean_slowdown", "mean_slowdown_reduction_pct", "seeds_token_lower_slowdown", "n_seeds"]],
         dict(base_total_faults=n, tok_total_faults=n, total_fault_reduction_pct=p0, base_mean_slowdown=d2,
              tok_mean_slowdown=d2, mean_slowdown_reduction_pct=p0))
t += "\nCases where the token policy is worse or equal are retained (see e.g. low shortage rows).\n\n"
t += "## 4. Section 5.4 example (53 MB + 58 MB arrays, 60 MB memory; scaled to 1/4)\n\n"
t += tab(s54p[["policy", "name", "major_faults", "elapsed", "dedicated", "slowdown", "false_lru_cross"]],
         dict(major_faults=n, elapsed=n, dedicated=n, slowdown=d2)) + "\n"
t += tab(s54s[["policy", "makespan", "cpu_utilisation", "total_major_faults", "token_acquisitions", "protected_skips",
               "fallback_evictions", "completion_order"]], dict(makespan=n, cpu_utilisation=d2, total_major_faults=n)) + "\n"
t += ("The baseline's slowdown is extreme because exact LRU on a cyclic scan larger than memory is its worst case "
      "(every reference faults); the paper's Linux baseline was less pathological. Read this as 'the mechanism behaves as the "
      "paper describes', not as a match to the paper's magnitude.\n\n")
t += "## 5. Policy overhead\n\n"
o = mainsys.groupby("policy").agg(victim_scan_steps=("victim_scan_steps", "mean"), policy_evictions=("policy_evictions", "mean"),
                                  wall_seconds=("wall_seconds", "mean")).reset_index()
t += tab(o, dict(victim_scan_steps=n, policy_evictions=n, wall_seconds=lambda v: f"{v:.2f}"))
t += ("\nVictim-scan steps are counted per policy call (the token policy performs an extra unrestricted scan only to count "
      "protection events, so its step count is inflated ~2x vs a production implementation). Wall-clock time is simulator "
      "runtime, NOT simulated time, and says nothing about kernel overhead (the paper reports it as negligible).\n")
(DOCS / "results.md").write_text(t)
print("wrote docs/results.md")
